-- ⚠️⚠️ বন্ধ মাস বাদ (R1) — ওখানে সংখ্যা নড়ানো যায় না, আর দরকারও নেই:
-- ওই মাসের কাগজ ইতিমধ্যেই বেরিয়ে গেছে।
INSERT INTO "summary_dirty" ("work_date")
SELECT max(d.work_date)
FROM "daily_summary" d
LEFT JOIN "month_closures" c
       ON c.year_month = to_char(d.work_date, 'YYYY-MM')
WHERE c.year_month IS NULL
GROUP BY to_char(d.work_date, 'YYYY-MM')
ON CONFLICT ("work_date") DO NOTHING;
