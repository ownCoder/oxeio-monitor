-- ⚠️⚠️ আগে soak মাপা হতো কেবল devices.agent_version_since থেকে — অর্থাৎ
-- ডিভাইসটা কবে বিল্ডটা বসিয়েছে। ঘড়িটা ধাপ বদলালে রিসেট হতো না, তাই
-- canary-তে ছ-ঘণ্টা পার করা একটা মেশিন পরের টিকেই partial → all-ও
-- করিয়ে দিত: ৫০% ধাপটা কার্যত এড়িয়ে যেত, আর "ধাপে ধাপে ছাড়া"র পুরো
-- উদ্দেশ্যটাই ব্যর্থ হতো।
ALTER TABLE "agent_versions"
    ADD COLUMN "stage_changed_at" TIMESTAMPTZ(3) NOT NULL DEFAULT now();

-- ⚠️ পুরোনো সারিতে now() বসলে প্রতিটা ভার্সন "এইমাত্র ধাপ বদলেছে" দাবি
-- করত, আর চলতি রোলআউট ছ-ঘণ্টার জন্য অকারণে আটকে যেত। released_at-ই
-- সবচেয়ে সৎ অনুমান: ওটাই ধাপের সবচেয়ে পুরোনো সম্ভাব্য শুরু।
UPDATE "agent_versions" SET "stage_changed_at" = "released_at";
