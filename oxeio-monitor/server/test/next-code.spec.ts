import { describe, expect, it } from 'vitest';

import { nextEmployeeCode } from '../src/admin/next-code';

/**
 * পরের কর্মী-কোডের পরামর্শ।
 *
 * ⚠️ এই ফাংশনের ভুল **নীরব**: ভুল কোড পরামর্শ দিলে সেভ করার সময় ৪০৯
 * আসে, আর মালিক ভাবেন সিস্টেম ভেঙে গেছে — অথচ শুধু একটা সংখ্যা এক কম
 * বলা হয়েছিল। তাই সীমানার কেসগুলোই এখানে বেশি।
 */
describe('nextEmployeeCode', () => {
  it('কেউ না থাকলে OX-001', () => {
    expect(nextEmployeeCode([])).toBe('OX-001');
  });

  it('ক্রম ধরে এগোয়', () => {
    expect(nextEmployeeCode(['OX-001', 'OX-002'])).toBe('OX-003');
  });

  /**
   * ⭐⭐ **আসল ডেটার কেস।** মালিকের তালিকায় দুই ধাঁচ পাশাপাশি —
   * `OX-001` (হাতে বসানো) আর `OX-01`…`OX-12` (seed থেকে)।
   *
   * ⚠️ "সবচেয়ে চওড়াটা নাও" ধরলে পরেরটা হতো `OX-013`, অর্থাৎ চলতি ক্রম
   * থেকে ছিটকে যেত। যেখানে থেমেছিলেন সেখান থেকেই এগোনো উচিত।
   */
  it('মিশ্র প্রস্থে সবচেয়ে বড় সংখ্যার ধাঁচ ধরে', () => {
    const codes = ['OX-001', 'OX-01', 'OX-02', 'OX-11', 'OX-12'];
    expect(nextEmployeeCode(codes)).toBe('OX-13');
  });

  it('ক্রম এলোমেলো থাকলেও সবচেয়ে বড়টাই ভিত্তি', () => {
    expect(nextEmployeeCode(['OX-07', 'OX-02', 'OX-11', 'OX-05'])).toBe('OX-12');
  });

  /** ⚠️ ৯৯ → ১০০: প্রস্থ ছাড়িয়ে গেলে কাটা যাবে না */
  it('প্রস্থ ছাড়িয়ে গেলে সংখ্যাটা বড় হয়', () => {
    expect(nextEmployeeCode(['OX-99'])).toBe('OX-100');
    expect(nextEmployeeCode(['OX-999'])).toBe('OX-1000');
  });

  /**
   * ⚠️ সংখ্যা-নয় এমন কোড থাকতেই পারে (`ADMIN`, `OX_5`, `INTERN-A`) —
   * ওগুলো বাদ যায়, নইলে `NaN` থেকে `OX-NaN` বেরোত।
   */
  it('ধাঁচে না পড়া কোড বাদ যায়', () => {
    expect(nextEmployeeCode(['ADMIN', 'INTERN-A', 'OX-04', 'X'])).toBe('OX-05');
  });

  it('সব কোডই ধাঁচের বাইরে হলে শুরু থেকে', () => {
    expect(nextEmployeeCode(['ADMIN', 'BOSS'])).toBe('OX-001');
  });

  /**
   * ⭐ উপসর্গ **সবচেয়ে প্রচলিতটা**, সবচেয়ে বড় কোডেরটা নয়।
   *
   * ⚠️ কেউ একবার `TMP-99` বসালে পরের সব পরামর্শ `TMP-` হয়ে যেত, অথচ
   * বাকি সবাই `OX-`।
   */
  it('উপসর্গ প্রচলিতটাই নেয়, বিচ্ছিন্নটা নয়', () => {
    const codes = ['OX-01', 'OX-02', 'OX-03', 'TMP-99'];
    expect(nextEmployeeCode(codes)).toBe('OX-100');
  });

  it('অন্য উপসর্গ হলে সেটাই ধরে রাখে', () => {
    expect(nextEmployeeCode(['EMP-05', 'EMP-06'])).toBe('EMP-07');
  });

  /** ⚠️ সামনে-পিছনে ফাঁকা জায়গা থাকতে পারে (হাতে বসানো ডেটা) */
  it('ফাঁকা জায়গা ছেঁকে নেয়', () => {
    expect(nextEmployeeCode([' OX-07 '])).toBe('OX-08');
  });

  /**
   * ⚠️⚠️ inactive কর্মীর কোডও ধরতে হবে — না ধরলে ছাঁটাই হওয়া কারো কোড
   * আবার পরামর্শ হতো, আর সেভ করতে গিয়ে ৪০৯। অথচ পর্দায় (active ফিল্টারে)
   * ওই কোডের কাউকে দেখা যেত না, তাই কারণটা বোঝাই যেত না।
   *
   * ⭐ ফাংশনটা নিজে active/inactive জানে না — **কলারের দায়িত্ব** সব কোড
   * পাঠানো। সেটা `employees.service.ts`-এ `where` ছাড়া query দিয়ে করা।
   */
  it('তালিকায় যা দেওয়া হবে তার সবই গোনা হয়', () => {
    expect(nextEmployeeCode(['OX-01', 'OX-09'])).toBe('OX-10');
  });
});
